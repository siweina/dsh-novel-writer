/**
 * 子串碰撞守卫表（v6.5.0 · 逐字重建）
 *
 * ## 为什么需要这张表
 *
 * 用语审计的判定是 `text.includes(word)`（`lib/index.js` 的 collectStyleCandidates），
 * 中文没有词边界，于是「词」与「恰好相邻的两个字」被当成同一件事。而禁用词表里
 * **93% 是 2 字词**，2 字中文词当子串的概率天然很高。
 *
 * ## 语义（判定逻辑，见 lib/core.js 的 isGuardedArtifact）
 *
 * 一个命中被判为**子串巧合**，当且仅当：
 *   · 该词**紧邻的前一个字/序列**在 `notBefore` / `notBeforeSeq` 里，或
 *   · 该词**紧邻的后一个字/序列**在 `notAfter` / `notAfterSeq` 里
 *
 * 例：`里正` 的 notBefore 含「这」→「这[里正]是」被判为巧合（这里 + 正是）；
 *     `在下` 的 notAfter 含「面」→「[在下]面」被判为巧合（在 + 下面）。
 *
 * ## 本轮重建的填字规则（v6.5.0）
 *
 * 设禁词 W = w1w2…wn，候选边界字为 X（前）或 Y（后）。
 *
 * **规则 A（构词）**——子串巧合的本质是 W 的两个字被拆进相邻的两个词里：
 *   · `notBefore` 收 X ⟺ **X + w1 是常用词**（这+里＝这里；心+里＝心里；文+官＝文官）
 *   · `notAfter`  收 Y ⟺ **wn + Y 是常用词**（人+物＝人物；下+面＝下面；教+头＝教头）
 *   反例（旧表的系统性错误）：把「W 后面能接什么」当成依据，于是收了
 *   `在下`+前（下前不是词）、`大人`+会（人会不是词）、`官人`+手（人手是词但此处是「官人手冷」）……
 *   这类字零收益、纯损失。
 *
 * **规则 B（实证）**——每个填入的字/序列都必须有一条 `evidence`（语料原句或构造句），
 *   且该句**确实被判为巧合**（test/guards-test.mjs 断言①）。举不出 evidence 的字一律删掉。
 *   语料 = F:/doment/corpus/books.jsonl（311 万字符真实网文），
 *   窗口统计可由 F:/doment/_cache/grebuild/windows.mjs、bigram.mjs 复现。
 *
 * **规则 C（不吃真用法）**——删掉字之前，先试着造一句「该词作**真词**用、且紧邻边界字
 *   恰好就是这个字」的句子；能造出来就写进 `trueUse`。测试②断言这些句子**不被挡住**——
 *   谁把这个字加回 `notBefore`/`notAfter`，测试立刻变红（这是「反向门禁」）。
 *   例：`在下`+前 →「[在下]前几日曾在贵府叨扰」；`大人`+会 →「[大人]会替我们做主的」。
 *
 * **两侧都成立就不填**：若某字既能构成碰撞、又能构成真用法（如 `老夫`+人：老夫人／老夫+人生），
 *   单字无法区分两者，按纪律**不填**，把该处交给「待判」档由模型读那一行判断。
 *
 * ## 数据形状
 *
 * ```js
 * "里正": guard({
 *   reason: "…",
 *   notBefore: ["这", "那"],        // 紧邻前一字命中即判巧合
 *   notBeforeSeq: ["平日"],          // 单字判不到时用序列（「平日里」是词，「昨日里」不是）
 *   evidenceBy: { "这": ["…[里正]是…"], "平日": ["…平日[里正]人…"] },  // 逐字/逐序列实证
 *   trueUse: { "心": ["关心[里正]的伤势…"] }                          // 被删掉的字：反例句
 * })
 * ```
 * `evidence`（扁平数组）由 `guard()` 自动从 `evidenceBy` 汇总——保留这个形状是为了让
 * `tools/audit/guard-probe.mjs`（它 `for (const ev of guard.evidence)`）继续可用；
 * 测试会断言两者严格一致，不会漂移。
 *
 * ## 本轮删除的整条守卫
 *
 * `圣器`（唯一候选字「神」：神+圣＝神圣 ✓ 但「诸神|圣器」也是真用法）、
 * `科举`（唯一候选字「行/办」：科举+行 是真用法「科举行于隋唐」）——
 * 按「两侧都成立就不填」整条移除，碰撞改走「待判」档。
 */

/** 由 evidenceBy 汇总出扁平 evidence（供 tools/audit/guard-probe.mjs 等既有消费方使用）。 */
function guard(spec) {
  const evidenceBy = spec.evidenceBy || {};
  return {
    ...spec,
    evidenceBy,
    evidence: [...new Set(Object.values(evidenceBy).flat())]
  };
}

